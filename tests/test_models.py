class TestCalculationLogModel:
    """Test CalculationLog model."""

    def test_create_log(self):
        log = CalculationLog(
            hts_code="8483.40",
            import_date=date(2026, 8, 1),
            origin_country="CN",
            input_data={"hts_code": "8483.40", "invoice_value_usd": 5000},
            matched_rules=["mfn-8483", "301-8483"],
            exclusions_applied=[],
            result_data={"landed_cost_usd": 6500},
        )
        assert log.hts_code == "8483.40"
        assert log.matched_rules == ["mfn-8483", "301-8483"]
        assert log.exclusions_applied == []
        assert log.result_data["landed_cost_usd"] == 6500
